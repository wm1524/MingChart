"""MingChart HTML 导出：生成交互式网页图表"""
import os

import plotly.graph_objects as go

from config import (
    CHART_PIE, CHART_BAR, CHART_LINE,
    APP_NAME, APP_VERSION, CHART_PALETTE,
)


class HtmlExporter:
    def export(self, chart_type, labels, values, options, filepath):
        title = options.get("title", "数据图表")
        bg = options.get("bg_color", "#ffffff")
        fg = options.get("fg_color", "#4a90e2")
        xlabel = options.get("xlabel", "类别")
        ylabel = options.get("ylabel", "数值")

        if chart_type == CHART_PIE:
            fig = self._build_pie(labels, values, title, bg)
        elif chart_type == CHART_BAR:
            fig = self._build_bar(labels, values, title, bg, fg, xlabel, ylabel)
        elif chart_type == CHART_LINE:
            fig = self._build_line(labels, values, title, bg, fg, xlabel, ylabel)
        else:
            raise ValueError(f"未知图表类型: {chart_type}")

        fig.update_layout(
            title=dict(
                text=title,
                font=dict(size=22, color="#262626", family="Microsoft YaHei"),
                x=0.5, xanchor="center"
            ),
            paper_bgcolor=bg,
            plot_bgcolor=bg,
            font=dict(family="Microsoft YaHei", size=13),
            hoverlabel=dict(
                bgcolor="#2c3e50",
                font_size=13,
                font_family="Microsoft YaHei",
                font_color="white",
                bordercolor="#2c3e50",
            ),
            margin=dict(l=70, r=40, t=80, b=70),
        )

        fig.add_annotation(
            text=f"Generated by {APP_NAME} v{APP_VERSION}",
            xref="paper", yref="paper",
            x=1, y=-0.12, showarrow=False,
            font=dict(size=10, color="#8c8c8c")
        )

        if not filepath.lower().endswith(".html"):
            filepath += ".html"

        fig.write_html(
            filepath,
            include_plotlyjs="cdn",
            full_html=True,
            config={
                "displaylogo": False,
                "responsive": True,
                "modeBarButtonsToRemove": ["lasso2d", "select2d"],
            }
        )
        return os.path.abspath(filepath)

    def _build_pie(self, labels, values, title, bg):
        fig = go.Figure(data=[go.Pie(
            labels=labels,
            values=values,
            hole=0.0,
            textinfo="label+percent",
            textposition="auto",
            marker=dict(
                colors=CHART_PALETTE[:len(values)],
                line=dict(color="white", width=2)
            ),
            hovertemplate="<b>%{label}</b><br>" +
                          "数值: %{value}<br>" +
                          "占比: %{percent}<extra></extra>",
        )])
        fig.update_traces(textfont_size=13)
        return fig

    def _build_bar(self, labels, values, title, bg, fg, xlabel, ylabel):
        fig = go.Figure(data=[go.Bar(
            x=labels,
            y=values,
            marker=dict(
                color=fg,
                line=dict(color="white", width=1.5)
            ),
            text=values,
            textposition="outside",
            hovertemplate="<b>%{x}</b><br>" +
                          f"{ylabel}: %{{y}}<extra></extra>",
        )])
        fig.update_layout(
            xaxis=dict(title=xlabel, showgrid=False, linecolor="#e1e4e8"),
            yaxis=dict(title=ylabel, showgrid=True,
                       gridcolor="#f0f0f0", zeroline=False),
        )
        return fig

    def _build_line(self, labels, values, title, bg, fg, xlabel, ylabel):
        fig = go.Figure(data=[go.Scatter(
            x=labels,
            y=values,
            mode="lines+markers+text",
            line=dict(color=fg, width=3, shape="spline"),
            marker=dict(
                size=12,
                color="white",
                line=dict(color=fg, width=2.5),
            ),
            text=values,
            textposition="top center",
            textfont=dict(size=11, color="#262626"),
            hovertemplate="<b>%{x}</b><br>" +
                          f"{ylabel}: %{{y}}<extra></extra>",
        )])
        fig.update_layout(
            xaxis=dict(title=xlabel, showgrid=False, linecolor="#e1e4e8"),
            yaxis=dict(title=ylabel, showgrid=True,
                       gridcolor="#f0f0f0", zeroline=False),
        )
        return fig